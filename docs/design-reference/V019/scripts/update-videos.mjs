/**
 * FIXLGS POE2 static snapshot updater; ported from V256 src/lib/youtube.ts.
 * Node 20+, no paid API, no extra packages.
 * Replaces video-data.js ONLY after 3 real official-channel IDs are parsed.
 * Failure leaves last known working snapshot untouched.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputFile = resolve(projectRoot, 'video-data.js');
const channelUrl = 'https://www.youtube.com/@playpathofexile/videos';
const requiredCount = 3;
const fixtureArg = process.argv.find(arg => arg.startsWith('--fixture='));
const fixturePath = fixtureArg ? resolve(fixtureArg.slice('--fixture='.length)) : null;
const dryRun = process.argv.includes('--dry-run');

function textOf(value) {
  if (!value || typeof value !== 'object') return '';
  if (typeof value.simpleText === 'string') return value.simpleText;
  if (Array.isArray(value.runs)) return value.runs.map(run => typeof run?.text === 'string' ? run.text : '').join('').trim();
  return '';
}
function isObject(value) { return value !== null && typeof value === 'object' && !Array.isArray(value); }
function initialData(html) {
  for (const marker of ['var ytInitialData = ', 'window["ytInitialData"] = ', 'ytInitialData = ']) {
    const idx = html.indexOf(marker);
    if (idx < 0) continue;
    const start = html.indexOf('{', idx + marker.length);
    if (start < 0) continue;
    let depth = 0, inString = false, escaped = false;
    for (let i = start; i < html.length; i++) {
      const char = html[i];
      if (inString) {
        if (escaped) escaped = false;
        else if (char === '\\') escaped = true;
        else if (char === '"') inString = false;
      } else if (char === '"') inString = true;
      else if (char === '{') depth++;
      else if (char === '}' && --depth === 0) {
        try { return JSON.parse(html.slice(start, i + 1)); } catch { break; }
      }
    }
  }
  return null;
}
function isLiveOrShort(renderer) {
  const web = renderer.navigationEndpoint?.commandMetadata?.webCommandMetadata;
  if (typeof web?.url === 'string' && web.url.includes('/shorts/')) return true;
  if (renderer.upcomingEventData || renderer.isLiveNow) return true;
  if (Array.isArray(renderer.thumbnailOverlays)) {
    for (const overlay of renderer.thumbnailOverlays) {
      const status = overlay?.thumbnailOverlayTimeStatusRenderer;
      if (!isObject(status)) continue;
      const style = typeof status.style === 'string' ? status.style.toUpperCase() : '';
      if (['SHORTS','LIVE','UPCOMING'].some(x => style.includes(x))) return true;
    }
  }
  const title = textOf(renderer.title).toLowerCase();
  return title.includes('#shorts') || title.includes(' shorts');
}
function collectVideos(node, result, seen) {
  if (Array.isArray(node)) { node.forEach(child => collectVideos(child, result, seen)); return; }
  if (!isObject(node)) return;
  for (const key of ['videoRenderer', 'gridVideoRenderer']) {
    const renderer = node[key];
    if (!isObject(renderer)) continue;
    const id = typeof renderer.videoId === 'string' ? renderer.videoId : '';
    if (!/^[\w-]{11}$/.test(id) || seen.has(id) || isLiveOrShort(renderer)) continue;
    seen.add(id);
    result.push({id, title: textOf(renderer.title) || textOf(renderer.headline) || 'Path of Exile', thumbnail:`https://i.ytimg.com/vi/${id}/hqdefault.jpg`});
  }
  Object.values(node).forEach(value => collectVideos(value, result, seen));
}
function outputText(videos) {
  return `/* Official Path of Exile channel video snapshot. Auto-generated by scripts/update-videos.mjs. */\nwindow.FIXLGS_POE2_VIDEOS = ${JSON.stringify(videos, null, 2)};\n`;
}
try {
  const html = fixturePath ? await readFile(fixturePath, 'utf8') : await (async () => {
    const res = await fetch(channelUrl, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/154 Safari/537.36',
        'Accept-Language': 'en-US,en;q=0.9'
      },
      signal: AbortSignal.timeout(25000)
    });
    if (!res.ok) throw new Error(`YouTube returned HTTP ${res.status}`);
    return res.text();
  })();
  const parsed = initialData(html);
  if (!parsed) throw new Error('ytInitialData was not found');
  const videos = [];
  collectVideos(parsed, videos, new Set());
  const selected = videos.slice(0, requiredCount);
  if (selected.length !== requiredCount) throw new Error(`Only ${selected.length} usable videos found; keeping previous snapshot`);
  const before = await readFile(outputFile, 'utf8').catch(() => '');
  const beforeIds = [...before.matchAll(/"id":\s*"([\w-]{11})"/g)].map(m => m[1]).slice(0,requiredCount);
  if (JSON.stringify(beforeIds) === JSON.stringify(selected.map(video => video.id))) {
    console.log('No new videos; snapshot unchanged. IDs:', selected.map(v => v.id).join(', '));
  } else if (dryRun) {
    console.log('Dry-run selected official videos:', JSON.stringify(selected));
  } else {
    await writeFile(outputFile, outputText(selected), 'utf8');
    console.log('Updated official videos:', JSON.stringify(selected));
  }
} catch (error) {
  console.error('Video refresh failed; original video-data.js is untouched:', error.message);
  process.exitCode = 1;
}
